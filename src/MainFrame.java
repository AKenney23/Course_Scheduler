    private void dropStudentSubmitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_dropStudentSubmitButtonActionPerformed
        // TODO add your handling code here:
        String name = (String)dropStudentComboBox.getSelectedItem();
        StudentEntry student = StudentQueries.getStudent(StudentQueries.findStudentID(name.substring(name.indexOf(",") + 1), name.substring(0, name.indexOf(","))));
        
        dropStudentTextArea.append((String)dropStudentComboBox.getSelectedItem() + " has been dropped from the list of students\n\n");
        
        for (String semester : SemesterQueries.getSemesterList()) {
            
            String droppedClasses = "";
            String scheduledClasses = "";
            
            for (ScheduleEntry entry : ScheduleQueries.getScheduleByStudent(semester, student.getStudentID())) {
                ScheduleQueries.dropStudentScheduleByCourse(semester, student.getStudentID(), entry.getCourseCode());
                
                String msg = "";
                if (entry.getStatus().equals("w")) {
                    msg = (String)dropStudentComboBox.getSelectedItem() + " has been dropped from the waitlist for " + entry.getCourseCode() + "\n";
                } else {
                    msg = (String)dropStudentComboBox.getSelectedItem() + " has been dropped from " + entry.getCourseCode() + "\n";
                }
                droppedClasses += msg;
                
                ArrayList<ScheduleEntry> waitlistedEntries = ScheduleQueries.getWaitlistedStudentsByClass(semester, entry.getCourseCode());
                if (!waitlistedEntries.isEmpty()) {
                    ScheduleQueries.updateScheduleEntry(waitlistedEntries.get(0));
                    StudentEntry updatedStudent = StudentQueries.getStudent(waitlistedEntries.get(0).getStudentID());
                    scheduledClasses += updatedStudent.getLastName() + ", " + updatedStudent.getFirstName() + " " + updatedStudent.getStudentID() + " has been scheduled into " + waitlistedEntries.get(0).getCourseCode() + "\n";
                }
            }
            if (!scheduledClasses.isEmpty() || !droppedClasses.isEmpty()) {
                dropStudentTextArea.append("For Semester: " + semester + "\n");
                dropStudentTextArea.append(droppedClasses);
                dropStudentTextArea.append(scheduledClasses);
            }
        }
        StudentQueries.dropStudent(StudentQueries.findStudentID(name.substring(name.indexOf(",") + 1), name.substring(0, name.indexOf(","))));
        rebuildStudentComboBoxes();
    }//GEN-LAST:event_dropStudentSubmitButtonActionPerformed

