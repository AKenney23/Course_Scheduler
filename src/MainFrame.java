    private void displayStudentScheduleButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_displayStudentScheduleButtonActionPerformed
        // TODO add your handling code here:
        String studentName = (String)displayScheduleSelectStudentComboBox.getSelectedItem();
        ArrayList<ScheduleEntry> studentSchedule = ScheduleQueries.getScheduleByStudent(currentSemester, StudentQueries.findStudentID(studentName.substring(studentName.indexOf(",") + 1), studentName.substring(0, studentName.indexOf(","))));
        DefaultTableModel tableModel = (DefaultTableModel)displayStudentScheduleJTable.getModel();
        tableModel.setNumRows(0);
        Object[] data = new Object[2];

        for (ScheduleEntry entry : studentSchedule) {
            data[0] = entry.getCourseCode();
            if (entry.getStatus().equals("w")) {
                data[1] = "Waitlisted";
            } else {
                data[1] = "Scheduled";
            }
            tableModel.addRow(data);
        }
    }//GEN-LAST:event_displayStudentScheduleButtonActionPerformed

    private void scheduleClassSubmitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_scheduleClassSubmitButtonActionPerformed
        // TODO add your handling code here:
        String status = "";
        String studentName = (String)scheduleClassSelectStudentComboBox.getSelectedItem();
        String course = (String)scheduleClassSelectClassComboBox.getSelectedItem();
        if (ScheduleQueries.getScheduledStudentCount(currentSemester, course) < ClassQueries.getClassSeats(currentSemester, course)) {
            status = "s";
            scheduleClassStatusLabel.setText(studentName + " has been scheduled for " + course);
        } else {
            status = "w";
            scheduleClassStatusLabel.setText(studentName + " has been waitlisted for " + course);
        }

        ScheduleQueries.addScheduleEntry(new ScheduleEntry(currentSemester, course, StudentQueries.findStudentID(studentName.substring(studentName.indexOf(",") + 1), studentName.substring(0, studentName.indexOf(","))), status, new java.sql.Timestamp(Calendar.getInstance().getTime().getTime())));
    }//GEN-LAST:event_scheduleClassSubmitButtonActionPerformed

    private void displayClassesButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_displayClassesButtonActionPerformed
        // TODO add your handling code here:
        ArrayList<ClassDescription> classList = MultiTableQueries.getAllClassDescriptions(currentSemester);
        DefaultTableModel table = (DefaultTableModel)displayClassJTable.getModel();
        table.setNumRows(0);
        Object[] data = new Object[3];

        for (ClassDescription classDesc : classList) {
            data[0] = classDesc.getCourseCode();
            data[1] = classDesc.getDescription();
            data[2] = classDesc.getSeats();
            table.addRow(data);
        }
    }//GEN-LAST:event_displayClassesButtonActionPerformed

